import { describe, expect, it, vi } from "vitest";
import { ArgumentError, isEmpty } from "@blazetrails/ruby-compat";
import { Group, type GroupClass } from "./group.js";
import { Base } from "./shell.js";
import type { ThorClass } from "./thor.js";
import { capture } from "./test-helpers/helper.js";
import * as groupFixtures from "./test-helpers/fixtures/group.js";
import * as invokeFixtures from "./test-helpers/fixtures/invoke.js";

type Klass = (new () => { baz(name: string): unknown }) & GroupClass & ThorClass;
const { MyCounter, BrokenCounter, WhinyGenerator, ChildGroup } = groupFixtures as unknown as Record<
  string,
  Klass
>;
const { E, F, G, H } = invokeFixtures as unknown as Record<string, Klass>;

describe("Thor::Group", () => {
  describe("command", () => {
    it("allows to use private methods from parent class as commands", async () => {
      expect(await ChildGroup.start()).toEqual(["bar", "foo", "baz"]);
      expect(new ChildGroup().baz("bar")).toEqual("bar");
    });
  });

  describe("#start", () => {
    it("invokes all the commands under the Thor group", async () => {
      expect(await MyCounter.start(["1", "2", "--third", "3"])).toEqual([
        1,
        2,
        3,
        null,
        null,
        null,
      ]);
    });

    it("uses argument's default value", async () => {
      expect(await MyCounter.start(["1", "--third", "3"])).toEqual([1, 2, 3, null, null, null]);
    });

    it("invokes all the commands in the Thor group and its parents", async () => {
      expect(await BrokenCounter.start(["1", "2", "--third", "3"])).toEqual([
        null,
        2,
        3,
        false,
        5,
        null,
      ]);
    });

    it("raises an error if a required argument is added after a non-required", () => {
      expect(() => MyCounter.argument("foo", { type: "string" })).toThrow(
        new ArgumentError(
          'You cannot have "foo" as required argument after the non-required argument "second".',
        ),
      );
    });

    it("raises when an exception happens within the command call", async () => {
      await expect(BrokenCounter.start(["1", "2", "--fail"])).rejects.toThrow(
        expect.objectContaining({
          constructor: TypeError,
          message: expect.stringMatching(/this_method_does_not_exist/),
        }),
      );
    });

    it("raises an error when a Thor group command expects arguments", async () => {
      await expect(WhinyGenerator.start()).rejects.toThrow(
        expect.objectContaining({
          constructor: ArgumentError,
          message: expect.stringMatching(/thor wrong_arity takes 1 argument, but it should not/),
        }),
      );
    });

    it("invokes help message if any of the shortcuts are given", async () => {
      const help = vi.spyOn(MyCounter, "help").mockImplementation(() => {});
      try {
        await MyCounter.start(["-h"]);
        expect(help).toHaveBeenCalled();
      } finally {
        help.mockRestore();
      }
    });
  });

  describe("#desc", () => {
    it("sets the description for a given class", () => {
      expect(MyCounter.desc()).toEqual(
        "Description:\n  This generator runs three commands: one, two and three.\n",
      );
    });

    it("can be inherited", () => {
      expect(BrokenCounter.desc()).toEqual(
        "Description:\n  This generator runs three commands: one, two and three.\n",
      );
    });

    it("can be nil", () => {
      expect(WhinyGenerator.desc()).toBeNull();
    });
  });

  describe("#help", () => {
    const content = () => capture(":stdout", () => MyCounter.help(new Base.shell!()));

    it("provides usage information", async () => {
      expect(await content()).toMatch(/my_counter N \[N\]/);
    });

    it("shows description", async () => {
      const c = await content();
      expect(c).toMatch(/Description:/);
      expect(c).toMatch(/This generator runs three commands: one, two and three./);
    });

    it("shows options information", async () => {
      const c = await content();
      expect(c).toMatch(/Options/);
      expect(c).toMatch(/\[--third=THREE\]/);
    });
  });

  describe("#invoke", () => {
    const content = () => capture(":stdout", () => E.start());

    it("allows to invoke a class from the class binding", async () => {
      expect(await content()).toMatch(/1\n2\n3\n4\n5\n/);
    });

    it("shows invocation information to the user", async () => {
      expect(await content()).toMatch(/invoke {2}Defined/);
    });

    it("uses padding on status generated by the invoked class", async () => {
      expect(await content()).toMatch(/finished {4}counting/);
    });

    it("allows invocation to be configured with blocks", async () => {
      await capture(":stdout", async () => {
        expect(await F.start()).toEqual(["Valim, Jose"]);
      });
    });

    it("shows invoked options on help", async () => {
      const content = await capture(":stdout", () => E.help(new Base.shell!()));
      expect(content).toMatch(/Defined options:/);
      expect(content).toMatch(/\[--unused\]/);
      expect(content).toMatch(/# This option has no use/);
    });
  });

  describe("#invoke_from_option", () => {
    describe("with default type", () => {
      const content = () => capture(":stdout", () => G.start());

      it("allows to invoke a class from the class binding by a default option", async () => {
        expect(await content()).toMatch(/1\n2\n3\n4\n5\n/);
      });

      it("does not invoke if the option is nil", async () => {
        expect(await capture(":stdout", () => G.start(["--skip-invoked"]))).not.toMatch(/invoke/);
      });

      it("prints a message if invocation cannot be found", async () => {
        const content = await capture(":stdout", () => G.start(["--invoked", "unknown"]));
        expect(content).toMatch(/error {2}unknown \[not found\]/);
      });

      it("allows to invoke a class from the class binding by the given option", async () => {
        let error: string | null = null;
        const content = await capture(":stdout", async () => {
          error = await capture(":stderr", () => G.start(["--invoked", "e"]));
        });
        expect(content).toMatch(/invoke {2}e/);
        expect(error).toMatch(/ERROR: "thor two" was called with arguments/);
      });

      it("shows invocation information to the user", async () => {
        expect(await content()).toMatch(/invoke {2}defined/);
      });

      it("uses padding on status generated by the invoked class", async () => {
        expect(await content()).toMatch(/finished {4}counting/);
      });

      it("shows invoked options on help", async () => {
        const content = await capture(":stdout", () => G.help(new Base.shell!()));
        expect(content).toMatch(/defined options:/);
        expect(content).toMatch(/\[--unused\]/);
        expect(content).toMatch(/# This option has no use/);
      });
    });

    describe("with boolean type", () => {
      const content = () => capture(":stdout", () => H.start());

      it("allows to invoke a class from the class binding by a default option", async () => {
        expect(await content()).toMatch(/1\n2\n3\n4\n5\n/);
      });

      it("does not invoke if the option is false", async () => {
        expect(await capture(":stdout", () => H.start(["--no-defined"]))).not.toMatch(/invoke/);
      });

      it("shows invocation information to the user", async () => {
        expect(await content()).toMatch(/invoke {2}defined/);
      });

      it("uses padding on status generated by the invoked class", async () => {
        expect(await content()).toMatch(/finished {4}counting/);
      });

      it("shows invoked options on help", async () => {
        const content = await capture(":stdout", () => H.help(new Base.shell!()));
        expect(content).toMatch(/defined options:/);
        expect(content).toMatch(/\[--unused\]/);
        expect(content).toMatch(/# This option has no use/);
      });
    });
  });

  describe("#command_exists?", () => {
    it("returns true for a command that is defined in the class", () => {
      expect(MyCounter.isCommandExists("one")).toBe(true);
    });

    it("returns false for a command that is not defined in the class", () => {
      expect(MyCounter.isCommandExists("zero")).toBe(false);
    });
  });

  describe("edge-cases", () => {
    it("can handle boolean options followed by arguments", async () => {
      const klass = class extends Group {
        declare name: string;
        declare options: Record<string, unknown>;

        static {
          const klass = this as unknown as Klass;
          klass.desc("say hi to name");
          klass.argument("name", { type: "string" });
          klass.classOption("loud", { type: "boolean" });
          klass.methodAdded("hi");
        }

        hi() {
          if (this.options["loud"]) this.name = this.name.toUpperCase();
          return `Hi ${this.name}`;
        }
      } as unknown as Klass;

      expect(await klass.start(["jose"])).toEqual(["Hi jose"]);
      expect(await klass.start(["jose", "--loud"])).toEqual(["Hi JOSE"]);
      expect(await klass.start(["--loud", "jose"])).toEqual(["Hi JOSE"]);
    });

    it("provides extra args as `args`", async () => {
      const klass = class extends Group {
        declare name: string;
        declare args: string[];
        declare options: Record<string, unknown>;

        static {
          const klass = this as unknown as Klass;
          klass.desc("say hi to name");
          klass.argument("name", { type: "string" });
          klass.classOption("loud", { type: "boolean" });
          klass.methodAdded("hi");
        }

        hi() {
          if (this.options["loud"]) this.name = this.name.toUpperCase();
          let out = `Hi ${this.name}`;
          if (!isEmpty(this.args)) out += ": " + this.args.join(", ");
          return out;
        }
      } as unknown as Klass;

      expect(await klass.start(["jose"])).toEqual(["Hi jose"]);
      expect(await klass.start(["jose", "--loud"])).toEqual(["Hi JOSE"]);
      expect(await klass.start(["--loud", "jose"])).toEqual(["Hi JOSE"]);
    });
  });
});
