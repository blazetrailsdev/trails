import { beforeEach, describe, expect, it } from "vitest";
import { Field } from "../lib/field.js";
import type { ContentTypeField } from "../lib/fields/content-type-field.js";
import { UnstructuredField } from "../lib/fields/unstructured-field.js";
import "../lib/index.js";
import { Mail } from "../lib/mail.js";
import { Part } from "../lib/part.js";
import { Utilities } from "../lib/utilities.js";

describe("Mail::Part", () => {
  it("should not add a default Content-ID", () => {
    const part = new Part();
    part.toString();
    expect(part.contentId()).toBeNull();
  });

  it("should not add a default Content-ID to non-inline attachments", () => {
    const part = new Part({ contentDisposition: "attachment" });
    part.toString();
    expect(part.contentId()).toBeNull();
  });

  it("should add a default Content-ID to inline attachments", () => {
    const part = new Part({ contentDisposition: "inline" });
    part.toString();
    expect(part.contentId()).not.toBeNull();
  });

  it("should not add a Date, MIME-Version, or Message-ID", () => {
    const part = new Part();
    part.toString();
    expect(part.date()).toBeNull();
    expect(part.mimeVersion()).toBeNull();
    expect(part.messageId()).toBeNull();
  });

  it("should preserve any content id that you put into it", () => {
    const part = new Part(function (this: Part) {
      this.contentId("<thisis@acontentid>");
      this.body("This is Text");
    });
    expect(part.contentId()).toEqual("<thisis@acontentid>");
  });

  it("should return an inline content_id", () => {
    const part = new Part(function (this: Part) {
      this.contentId("<thisis@acontentid>");
      this.body("This is Text");
    });
    expect(part.cid()).toEqual("thisis@acontentid");
  });

  it("should URL escape its inline content_id", () => {
    const part = new Part(function (this: Part) {
      this.contentId("<thi%%sis@acontentid>");
      this.body("This is Text");
    });
    expect(part.cid()).toEqual("thi%25%25sis@acontentid");
  });

  it("should add a content_id if there is none and is asked for an inline_content_id", () => {
    const part = new Part();
    expect(part.cid()).not.toBeNull();
  });

  it("should respond correctly to inline?", () => {
    let part = new Part({ contentDisposition: "attachment" });
    expect(part.isInline()).toBeFalsy();

    part = new Part({ contentDisposition: "inline" });
    expect(part.isInline()).toBeTruthy();
  });

  it("handles un-parsable content_disposition headers", () => {
    const part = new Part();
    const field = new Field("content-disposition");
    field.field = new UnstructuredField("content-disposition", "failed to parse");
    part.header().fields.push(field);
    expect(part.isInline()).toBeFalsy();
  });

  describe("parts that have a missing header", () => {
    it("should not try to init a header if there is none", async () => {
      await expect(
        () =>
          new Part(
            Utilities.toCrlf(`
The original message was received at Mon, 24 Dec 2007 10:03:47 +1100
from 60-0-0-146.static.tttttt.com.au [60.0.0.146]

This message was generated by mail12.tttttt.com.au

   ----- The following addresses had permanent fatal errors -----
<edwin@zzzzzzz.com>
    (reason: 553 5.3.0 <edwin@zzzzzzz.com>... Unknown E-Mail Address)

   ----- Transcript of session follows -----
... while talking to mail.zzzzzz.com.:
>>> DATA
<<< 553 5.3.0 <edwin@zzzzzzz.com>... Unknown E-Mail Address
550 5.1.1 <edwin@zzzzzzz.com>... User unknown
<<< 503 5.0.0 Need RCPT (recipient)

-- 
This message has been scanned for viruses and
dangerous content by MailScanner, and is
believed to be clean.
`),
          ),
      ).not.toOutput(undefined, "stderr");
    });
  });

  describe("delivery status reports", () => {
    let deliveryReport: Part;
    beforeEach(() => {
      deliveryReport = new Part(
        Utilities.toCrlf(`Content-Type: message/delivery-status

Reporting-MTA: dns; mail12.rrrr.com.au
Received-From-MTA: DNS; 60-0-0-146.static.tttttt.com.au
Arrival-Date: Mon, 24 Dec 2007 10:03:47 +1100

Final-Recipient: RFC822; edwin@zzzzzzz.com
Action: failed
Status: 5.3.0
Remote-MTA: DNS; mail.zzzzzz.com
Diagnostic-Code: SMTP; 553 5.3.0 <edwin@zzzzzzz.com>... Unknown E-Mail Address
Last-Attempt-Date: Mon, 24 Dec 2007 10:03:53 +1100
`),
      );
    });

    it("should know if it is a delivery-status report", () => {
      expect(deliveryReport.isDeliveryStatusReportPart()).toBeTruthy();
    });

    it("should create a delivery_status_data header object", () => {
      expect(deliveryReport.deliveryStatusData()).not.toBeNull();
    });

    it("should be bounced", () => {
      expect(deliveryReport.isBounced()).toBeTruthy();
    });

    it("should say action 'delayed'", () => {
      expect(deliveryReport.action()).toEqual("failed");
    });

    it("should give a final recipient", () => {
      expect(deliveryReport.finalRecipient()).toEqual("RFC822; edwin@zzzzzzz.com");
    });

    it("should give an error code", () => {
      expect(deliveryReport.errorStatus()).toEqual("5.3.0");
    });

    it("should give a diagostic code", () => {
      expect(deliveryReport.diagnosticCode()).toEqual(
        "SMTP; 553 5.3.0 <edwin@zzzzzzz.com>... Unknown E-Mail Address",
      );
    });

    it("should give a remote-mta", () => {
      expect(deliveryReport.remoteMta()).toEqual("DNS; mail.zzzzzz.com");
    });

    it("should be retryable", () => {
      expect(deliveryReport.isRetryable()).toBeFalsy();
    });

    describe("on a part without a certain field", () => {
      beforeEach(() => {
        deliveryReport = new Part(
          Utilities.toCrlf(`Content-Type: message/delivery-status

Reporting-MTA: dns; mail12.rrrr.com.au
Received-From-MTA: DNS; 60-0-0-146.static.tttttt.com.au
Arrival-Date: Mon, 24 Dec 2007 10:03:47 +1100

Final-Recipient: RFC822; edwin@zzzzzzz.com
Action: failed
Status: 5.3.0
Remote-MTA: DNS; mail.zzzzzz.com
Last-Attempt-Date: Mon, 24 Dec 2007 10:03:53 +1100
`),
        );
      });

      it("returns nil", () => {
        expect(deliveryReport.diagnosticCode()).toBeNull();
      });
    });
  });

  it("should correctly parse plain text raw source and not truncate after newlines - issue 208", () => {
    const plainText = "First Line\n\nSecond Line\n\nThird Line\n\n";
    const part = new Part(plainText);
    expect((part.get("content_type") as unknown as ContentTypeField).contentType()).toEqual(
      "text/plain",
    );
    expect(part.toString()).toMatch(/^First Line\r\n\r\nSecond Line\r\n\r\nThird Line/m);
  });

  describe("negotiating transfer encoding", () => {
    const lastEncoding = (s: string) =>
      [...s.matchAll(/Content-Transfer-Encoding: (.+)\r$/gm)].at(-1)![1];

    it("doesn't override part encoding when it's compatible with message", () => {
      const mail = Mail.new();
      const part = new Part();
      part.header().set("content_disposition", 'attachment; filename="unnamed"');
      part.setContentType("text/plain");
      part.setBody("a".repeat(999));
      part.body().setEncoding("base64");
      mail.body().push(part);

      expect(lastEncoding(mail.toString())).toEqual("base64");
    });

    it("retains specified encoding even though it isn't lowest cost", () => {
      const part = new Part();
      part.header().set("content_disposition", 'attachment; filename="unnamed"');
      part.setContentType("text/plain");
      part.setBody("a".repeat(999));
      part.body().setEncoding("base64");

      expect(lastEncoding(part.toString())).toEqual("base64");
    });
  });
});
