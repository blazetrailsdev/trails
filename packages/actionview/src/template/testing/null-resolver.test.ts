import { describe, it } from "vitest";
import { assertEqual, assertNil } from "@blazetrails/activesupport";
import { NullResolver } from "../../testing/resolvers.js";

describe("NullResolverTest", () => {
  it("should return template for any path", () => {
    const resolver = new NullResolver();
    const templates = resolver.findAll("path.tse", "arbitrary", false, {
      locale: [],
      formats: [":html"],
      handlers: [],
    });
    assertEqual(1, templates.length, "expected one template");
    assertEqual("Template generated by Null Resolver", templates[0].source);
    assertEqual("arbitrary/path.tse", String(templates[0].virtualPath));
    assertNil(templates[0].format);
  });
});
