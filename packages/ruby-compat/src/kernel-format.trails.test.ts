const ERRORS: [args: [string, ...unknown[]], expected: Error][] = [
  [["%s"], new ArgumentError("too few arguments")],
  [["%5%"], new ArgumentError("invalid format character - %")],
  [["%"], new ArgumentError("incomplete format specifier; use %% (double %) instead")],
  [["%d", "1.5"], new ArgumentError('invalid value for Integer(): "1.5"')],
  [["%d", null], new TypeError("can't convert nil into Integer")],
  [["%d", true], new TypeError("can't convert true into Integer")],
  [["%f", "x"], new ArgumentError('invalid value for Float(): "x"')],
  [["%x", -Infinity], new FloatDomainError("-Infinity")],
  [["%1$s %s", "a", "b"], new ArgumentError("unnumbered(1) mixed with numbered")],
  [["%s %1$s", "a", "b"], new ArgumentError("numbered(1) after unnumbered(1)")],
  [["%<foo>s %s", { ":foo": 1 }], new ArgumentError("unnumbered(1) mixed with named")],
  [["%0$s", "a"], new ArgumentError("malformed format string - %$")],
  [["%<bar>s", { ":foo": 1 }], new KeyError("key<bar> not found")],
  [["%{bar}", { ":foo": 1 }], new KeyError("key{bar} not found")],
  [["%<foo", { ":foo": 1 }], new ArgumentError("malformed name - unmatched parenthesis")],
  [["%5.2%"], new ArgumentError("invalid format character - %")],
  [["%q", 1], new ArgumentError("malformed format string - %q")],
];

describe("format", () => {
  it.each(CASES)("format(%s, ...) is %s", (args, expected) => {
    expect(format(...args)).toBe(expected);
  });

  it.each(ERRORS)("format(%s, ...) raises", (args, expected) => {
    expect(() => format(...args)).toThrow(
      expect.objectContaining({ name: expected.name, message: expected.message }),
    );
  });

  it("is the same function as sprintf", () => {
    expect(sprintf).toBe(format);
    expect(sprintf("%05.2f", 1.5)).toBe("01.50");
  });
});
