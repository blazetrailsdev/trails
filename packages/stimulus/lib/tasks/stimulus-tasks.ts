import { DSL, Task } from "@blazetrails/rake";
import {
  File,
  RbConfig,
  STDOUT as $stdout,
  TopLevel,
  block,
  rbFSystem,
} from "@blazetrails/ruby-compat";
import { Manifest } from "../manifest.js";
import { Stimulus } from "../stimulus-trails.js";

export const Tasks = {
  async runStimulusInstallTemplate(path: string): Promise<boolean | null> {
    return rbFSystem(
      RbConfig.ruby(),
      "./bin/trails",
      "app:template",
      `LOCATION=${File.expandPath(`../install/${path}${File.extname(import.meta.filename)}`, import.meta.dirname)}`,
    );
  },

  async isUsingBun(): Promise<boolean> {
    return File.isExistAsync(TopLevel.Trails!.root()!.join("bun.config.js").toString());
  },
};

Stimulus.Tasks = Tasks;

DSL.namespace("stimulus", () => {
  DSL.desc("Install Stimulus into the app");
  DSL.task(
    "install",
    block(async () => {
      if (
        (await File.isExistAsync(TopLevel.Trails!.root()!.join("package.json").toString())) &&
        (await Stimulus.Tasks.isUsingBun())
      ) {
        await (await Task.get("stimulus:install:bun")).invoke();
      } else if (
        await File.isExistAsync(TopLevel.Trails!.root()!.join("package.json").toString())
      ) {
        await (await Task.get("stimulus:install:node")).invoke();
      } else {
        $stdout.puts(
          "You must either be running with node (package.json) or importmap-rails (config/importmap.rb) to use this gem.",
        );
      }
    }),
  );

  DSL.namespace("install", () => {
    DSL.desc("Install Stimulus on an app running node");
    DSL.task(
      "node",
      block(async () => {
        await Stimulus.Tasks.runStimulusInstallTemplate("stimulus-with-node");
      }),
    );

    DSL.desc("Install Stimulus on an app running bun");
    DSL.task(
      "bun",
      block(async () => {
        await Stimulus.Tasks.runStimulusInstallTemplate("stimulus-with-bun");
      }),
    );
  });

  DSL.namespace("manifest", () => {
    DSL.desc("Show the current Stimulus manifest (all installed controllers)");
    DSL.task(
      "display",
      block(async () => {
        $stdout.puts(
          await Manifest.generateFrom(TopLevel.Trails!.root()!.join("app/javascript/controllers")),
        );
      }),
    );

    DSL.desc("Update the Stimulus manifest (will overwrite controllers/index.js)");
    DSL.task(
      "update",
      block(async () => {
        const manifest = await Manifest.generateFrom(
          TopLevel.Trails!.root()!.join("app/javascript/controllers"),
        );

        await File.openAsync(
          TopLevel.Trails!.root()!.join("app/javascript/controllers/index.js").toString(),
          "w+",
          (index) => {
            index.puts("// This file is auto-generated by ./bin/trails stimulus:manifest:update");
            index.puts("// Run that command whenever you add a new controller or create them with");
            index.puts("// ./bin/trails generate stimulus controllerName");
            index.puts();
            index.puts(`import { application } from "./application"`);
            index.puts(manifest);
          },
        );
      }),
    );
  });
});
