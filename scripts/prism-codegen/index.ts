let parsePromise:
  | Promise<
      (src: string) => {
        value: unknown;
      }
    >
  | undefined;
async function getParser() {
  if (!parsePromise) parsePromise = loadPrism();
  return parsePromise;
}
export interface GenResult {
  code: string;
  coverage: Coverage;
  perDef: Map<
    string,
    {
      total: number;
      passthrough: number;
    }
  >;
  parseErrorCount: number;
}
const HEADER =
  "// GENERATED by scripts/prism-codegen (deterministic spike). Not compiled or tested,\n" +
  "// but parse-clean by construction (emitted via the TypeScript AST factory).\n" +
  "// Regenerate with `pnpm codegen:generate`. Do not edit by hand.\n\n";
export async function generateFromSource(
  rubySource: string,
  asyncMethods: ReadonlySet<string> = new Set(),
  runtimeImportPath = "./runtime.js",
  inheritedDelegations: DelegationTable = new Map(),
  linearization: Linearization | null = null,
  portMethods: ReadonlySet<string> = new Set(),
): Promise<GenResult> {
  const parse = await getParser();
  const result = parse(rubySource);
  const program = result.value as PrismNode;
  const delegations = mergeDelegations(inheritedDelegations, collectDelegations(program));
  const gen = new Codegen(defaultRegistry(), asyncMethods, delegations, linearization, portMethods);
  const statements = gen.stmt(program, false);
  const sourceFile = ts.factory.createSourceFile(
    statements,
    ts.factory.createToken(ts.SyntaxKind.EndOfFileToken),
    ts.NodeFlags.None,
  );
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  let helperImport = "";
  if (gen.helpers.size > 0) {
    const names = [...gen.helpers].sort().join(", ");
    helperImport = `import { ${names} } from "${runtimeImportPath}";\n\n`;
  }
  const code = HEADER + helperImport + printer.printFile(sourceFile);
  return {
    code,
    coverage: gen.coverage,
    perDef: gen.perDef,
    parseErrorCount: countParseErrors(code),
  };
}
export function countParseErrors(code: string): number {
  const reparsed = ts.createSourceFile(
    "gen.js",
    code,
    ts.ScriptTarget.ESNext,
    true,
    ts.ScriptKind.JS,
  );
  return (
    (
      reparsed as unknown as {
        parseDiagnostics?: ts.Diagnostic[];
      }
    ).parseDiagnostics ?? []
  ).length;
}
/** Awaits that land in a function not marked `async` — invalid JS the printer cannot catch. */
export function countAwaitsOutsideAsync(code: string): number {
  const source = ts.createSourceFile(
    "gen.js",
    code,
    ts.ScriptTarget.ESNext,
    true,
    ts.ScriptKind.JS,
  );
  let count = 0;
  const walk = (node: ts.Node, inAsync: boolean): void => {
    if (ts.isAwaitExpression(node) && !inAsync) count += 1;
    const isFunction =
      ts.isFunctionDeclaration(node) ||
      ts.isFunctionExpression(node) ||
      ts.isArrowFunction(node) ||
      ts.isMethodDeclaration(node) ||
      ts.isGetAccessorDeclaration(node) ||
      ts.isSetAccessorDeclaration(node) ||
      ts.isConstructorDeclaration(node);
    const scope = isFunction
      ? ((node as { modifiers?: readonly ts.ModifierLike[] }).modifiers ?? []).some(
          (m) => m.kind === ts.SyntaxKind.AsyncKeyword,
        )
      : inAsync;
    node.forEachChild((child) => walk(child, scope));
  };
  walk(source, true);
  return count;
}
