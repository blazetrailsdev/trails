# Writes packages/mail/src/multibyte/simple-case-mappings.generated.ts from the
# gem's Mail::Multibyte UnicodeDatabase (`values/unicode_tables.dat`), UnicodeData
# fields 12 and 13. Run: ruby scripts/generate-mail-simple-case-mappings.rb
module Mail; module Multibyte; module Unicode
  class Codepoint
    attr_accessor :code, :combining_class, :decomp_type, :decomp_mapping,
                  :uppercase_mapping, :lowercase_mapping
  end
end; end; end

root = File.expand_path("..", __dir__)
codepoints, = Marshal.load(File.binread("#{root}/vendor/mail/2.8.1/lib/mail/values/unicode_tables.dat"))
table = lambda do |field|
  codepoints.sort.filter_map { |cp, c| (m = c.send(field)) && m > 0 ? "#{cp.to_s(36)}:#{(m - cp).to_s(36)}" : nil }.join(",")
end
File.write("#{root}/packages/mail/src/multibyte/simple-case-mappings.generated.ts", <<~TS)
  // Generated by scripts/generate-mail-simple-case-mappings.rb. Do not edit.
  function decode(table: string): ReadonlyMap<number, number> {
    return new Map(
      table.split(",").map((entry) => {
        const [cp, delta] = entry.split(":").map((n) => parseInt(n, 36));
        return [cp, cp + delta];
      }),
    );
  }

  export const UPPERCASE_MAPPING = decode(
    "#{table.call(:uppercase_mapping)}",
  );

  export const LOWERCASE_MAPPING = decode(
    "#{table.call(:lowercase_mapping)}",
  );
TS
